package gosql

import (
	"fmt"
	"strconv"
	"strings"
)

// CodeGenerator 代码生成器，将 AST 编译为纯静态 Go 函数。
// 所有表达式在代码生成阶段编译为原生 Go 代码，运行时不需要解释器。
// define 块编译为独立函数，use 编译为直接函数调用。
type CodeGenerator struct {
	bufs        []*strings.Builder // 缓冲区栈（用于 define 函数生成时切换）
	indent      int
	varCounter  int
	pkgPrefix   string             // "gosql." (外部包) 或 "" (gosql 包内)
	knownKeys   map[string]string  // 模板 key -> 函数名
	funcPrefix  string             // 当前函数名前缀（用于嵌套 define）
	defineFuncs []string           // 收集的 define 函数代码
}

// NewCodeGenerator 创建代码生成器
// pkgPrefix: "gosql." 表示生成代码在外部包（import gosql），"" 表示在 gosql 包内
func NewCodeGenerator(pkgPrefix string) *CodeGenerator {
	return &CodeGenerator{
		pkgPrefix: pkgPrefix,
		knownKeys: make(map[string]string),
	}
}

// GenerateFile 从模板列表生成完整的 Go 源文件
// buildTag 可选，非空时在文件头部添加 //go:build 标签
func (g *CodeGenerator) GenerateFile(templates []*SQLTemplate, asts map[string]*TemplateAST, packageName, sourceFile string, buildTag ...string) (string, error) {
	type funcEntry struct {
		key      string
		funcName string
		code     string
	}

	// 第一步：建立已知模板映射（用于 @use 直接调用）
	for _, tmpl := range templates {
		key := tmpl.Namespace + "." + tmpl.Name
		g.knownKeys[key] = sanitizeFuncName(key)
	}

	var entries []funcEntry
	g.defineFuncs = nil

	// 第二步：为每个模板生成函数
	for _, tmpl := range templates {
		key := tmpl.Namespace + "." + tmpl.Name
		ast, ok := asts[key]
		if !ok {
			continue
		}

		funcName := g.knownKeys[key]

		// 重置状态
		g.bufs = []*strings.Builder{{}}
		g.indent = 1
		g.varCounter = 0
		g.funcPrefix = funcName

		// 生成函数体
		if err := g.generateNodes(ast.Nodes); err != nil {
			return "", fmt.Errorf("generating %s: %w", key, err)
		}

		// 构建完整函数
		var funcCode strings.Builder
		funcCode.WriteString(fmt.Sprintf("func %s(ctx *%sStaticContext) (retErr error) {\n", funcName, g.pkgPrefix))
		funcCode.WriteString("\tdefer ctx.Recover(&retErr)\n\n")
		funcCode.WriteString(g.buf().String())
		funcCode.WriteString("\treturn nil\n")
		funcCode.WriteString("}\n")

		entries = append(entries, funcEntry{
			key:      key,
			funcName: funcName,
			code:     funcCode.String(),
		})
	}

	// 第三步：构建完整文件
	var result strings.Builder
	result.WriteString("// Code generated by gosqlgen. DO NOT EDIT.\n")
	result.WriteString(fmt.Sprintf("// Source: %s\n\n", sourceFile))

	// 可选 build tag
	if len(buildTag) > 0 && buildTag[0] != "" {
		result.WriteString(fmt.Sprintf("//go:build %s\n\n", buildTag[0]))
	}

	result.WriteString(fmt.Sprintf("package %s\n\n", packageName))

	// 导入
	if g.pkgPrefix != "" {
		result.WriteString("import (\n")
		result.WriteString("\t\"github.com/llyb120/gosql\"\n")
		result.WriteString(")\n\n")
	}

	// init 函数（仅注册模板函数，不注册 define）
	result.WriteString("func init() {\n")
	for _, entry := range entries {
		result.WriteString(fmt.Sprintf("\t%sRegisterStatic(%s, %s)\n",
			g.pkgPrefix, strconv.Quote(entry.key), entry.funcName))
	}
	result.WriteString("}\n\n")

	// 输出模板函数
	for _, entry := range entries {
		result.WriteString(entry.code)
		result.WriteString("\n")
	}

	// 输出 define 函数
	for _, defCode := range g.defineFuncs {
		result.WriteString(defCode)
		result.WriteString("\n")
	}

	return result.String(), nil
}

// ==================== 缓冲区管理 ====================

func (g *CodeGenerator) buf() *strings.Builder {
	return g.bufs[len(g.bufs)-1]
}

func (g *CodeGenerator) pushBuf() {
	g.bufs = append(g.bufs, &strings.Builder{})
}

func (g *CodeGenerator) popBuf() string {
	result := g.bufs[len(g.bufs)-1].String()
	g.bufs = g.bufs[:len(g.bufs)-1]
	return result
}

// writeLine 写入一行带缩进的代码
func (g *CodeGenerator) writeLine(format string, args ...interface{}) {
	b := g.buf()
	for i := 0; i < g.indent; i++ {
		b.WriteString("\t")
	}
	if len(args) > 0 {
		b.WriteString(fmt.Sprintf(format, args...))
	} else {
		b.WriteString(format)
	}
	b.WriteString("\n")
}

// ==================== 节点生成 ====================

func (g *CodeGenerator) generateNodes(nodes []Node) error {
	for _, node := range nodes {
		if err := g.generateNode(node); err != nil {
			return err
		}
	}
	return nil
}

func (g *CodeGenerator) generateNode(node Node) error {
	switch n := node.(type) {
	case *TextNode:
		return g.generateText(n)
	case *VarNode:
		return g.generateVar(n)
	case *VarExprNode:
		return g.generateVarExpr(n)
	case *RawNode:
		return g.generateRaw(n)
	case *RawExprNode:
		return g.generateRawExpr(n)
	case *IfNode:
		return g.generateIf(n)
	case *ForNode:
		return g.generateFor(n)
	case *CodeNode:
		return g.generateCode(n)
	case *UseNode:
		return g.generateUse(n)
	case *DefineNode:
		return g.generateDefine(n)
	case *ConditionalLineNode:
		return g.generateConditionalLine(n)
	case *FuncBlockNode:
		return g.generateFuncBlock(n)
	default:
		return fmt.Errorf("unknown node type: %T", node)
	}
}

// ==================== 文本节点 ====================

func (g *CodeGenerator) generateText(n *TextNode) error {
	if n.Text == "" {
		return nil
	}
	g.writeLine("ctx.WriteSQL(%s)", strconv.Quote(n.Text))
	return nil
}

// ==================== 变量节点 @var ====================

func (g *CodeGenerator) generateVar(n *VarNode) error {
	if n.Conditional {
		g.varCounter++
		v := fmt.Sprintf("_v%d", g.varCounter)
		ok := fmt.Sprintf("_ok%d", g.varCounter)
		g.writeLine("{")
		g.indent++
		g.writeLine("%s, %s := ctx.Get(%s)", v, ok, strconv.Quote(n.Name))
		g.writeLine("if !%s || !%sToBool(%s) {", ok, g.pkgPrefix, v)
		g.indent++
		g.writeLine("ctx.SkipCurrentLine()")
		g.indent--
		g.writeLine("} else {")
		g.indent++
		g.writeLine("ctx.AppendArg(%s)", v)
		g.indent--
		g.writeLine("}")
		g.indent--
		g.writeLine("}")
	} else {
		g.writeLine("ctx.AppendArg(ctx.MustGet(%s))", strconv.Quote(n.Name))
	}
	return nil
}

// ==================== 变量表达式节点 @{ expr } ====================

func (g *CodeGenerator) generateVarExpr(n *VarExprNode) error {
	exprCode, err := CompileValueExprToGo(n.Expr, g.pkgPrefix)
	if err != nil {
		return fmt.Errorf("compile var expr %q: %w", n.Expr, err)
	}

	if n.Conditional {
		g.varCounter++
		v := fmt.Sprintf("_v%d", g.varCounter)
		g.writeLine("{")
		g.indent++
		g.writeLine("%s := %s", v, exprCode)
		g.writeLine("if !%sToBool(%s) {", g.pkgPrefix, v)
		g.indent++
		g.writeLine("ctx.SkipCurrentLine()")
		g.indent--
		g.writeLine("} else {")
		g.indent++
		g.writeLine("ctx.AppendArg(%s)", v)
		g.indent--
		g.writeLine("}")
		g.indent--
		g.writeLine("}")
	} else {
		g.writeLine("ctx.AppendArg(%s)", exprCode)
	}
	return nil
}

