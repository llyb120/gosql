// ==================== if 节点 ====================

func (g *CodeGenerator) generateIf(n *IfNode) error {
	// 编译主条件
	condCode, err := CompileConditionToGo(n.Condition, g.pkgPrefix)
	if err != nil {
		return fmt.Errorf("compile if condition %q: %w", n.Condition, err)
	}

	g.writeLine("{")
	g.indent++

	g.varCounter++
	doneVar := fmt.Sprintf("_done%d", g.varCounter)
	g.writeLine("%s := false", doneVar)

	// 主 if 分支
	g.writeLine("if %s {", condCode)
	g.indent++
	if err := g.generateNodes(n.Body); err != nil {
		return err
	}
	g.writeLine("%s = true", doneVar)
	g.indent--
	g.writeLine("}")

	// else if 分支
	for _, elseIf := range n.ElseIf {
		elseCondCode, err := CompileConditionToGo(elseIf.Condition, g.pkgPrefix)
		if err != nil {
			return fmt.Errorf("compile else if condition %q: %w", elseIf.Condition, err)
		}
		g.writeLine("if !%s && %s {", doneVar, elseCondCode)
		g.indent++
		if err := g.generateNodes(elseIf.Body); err != nil {
			return err
		}
		g.writeLine("%s = true", doneVar)
		g.indent--
		g.writeLine("}")
	}

	// else 分支
	if n.Else != nil {
		g.writeLine("if !%s {", doneVar)
		g.indent++
		if err := g.generateNodes(n.Else.Body); err != nil {
			return err
		}
		g.indent--
		g.writeLine("}")
	}

	g.indent--
	g.writeLine("}")
	return nil
}

// ==================== for 节点 ====================

func (g *CodeGenerator) generateFor(n *ForNode) error {
	expr := strings.TrimSpace(n.Expr)
	if strings.Contains(expr, "range") {
		return g.generateForRange(n)
	}
	return g.generateForTraditional(n)
}

// generateForRange 生成 range 循环（编译为 gosql.Range + 闭包）
func (g *CodeGenerator) generateForRange(n *ForNode) error {
	info, err := ParseForRange(n.Expr, g.pkgPrefix)
	if err != nil {
		return fmt.Errorf("parse for range %q: %w", n.Expr, err)
	}

	g.varCounter++
	errVar := fmt.Sprintf("_forErr%d", g.varCounter)
	idxVar := fmt.Sprintf("_idx%d", g.varCounter)
	valVar := fmt.Sprintf("_val%d", g.varCounter)

	g.writeLine("if %s := %sRange(%s, func(%s, %s interface{}) error {",
		errVar, g.pkgPrefix, info.RangeCode, idxVar, valVar)
	g.indent++

	// 设置循环变量
	if info.IndexVar != "_" && info.IndexVar != "" {
		g.writeLine("ctx.Set(%s, %s)", strconv.Quote(info.IndexVar), idxVar)
	}
	if info.ValueVar != "_" && info.ValueVar != "" {
		g.writeLine("ctx.Set(%s, %s)", strconv.Quote(info.ValueVar), valVar)
	}

	// 生成循环体
	if err := g.generateNodes(n.Body); err != nil {
		return err
	}

	g.writeLine("return nil")
	g.indent--
	g.writeLine("}); %s != nil { return %s }", errVar, errVar)
	return nil
}

// generateForTraditional 生成传统 for 循环（编译为原生 Go for 循环）
func (g *CodeGenerator) generateForTraditional(n *ForNode) error {
	expr := strings.TrimSpace(n.Expr)
	parts := strings.Split(expr, ";")
	if len(parts) != 3 {
		return fmt.Errorf("invalid for expression: %s", expr)
	}

	initPart := strings.TrimSpace(parts[0])
	condPart := strings.TrimSpace(parts[1])
	postPart := strings.TrimSpace(parts[2])

	// 解析 init: i := 0
	initInfo, err := ParseForInit(initPart, g.pkgPrefix)
	if err != nil {
		return fmt.Errorf("parse for init: %w", err)
	}

	// 编译条件: i < 10
	condCode, err := CompileConditionToGo(condPart, g.pkgPrefix)
	if err != nil {
		return fmt.Errorf("compile for condition %q: %w", condPart, err)
	}

	// 解析 post: i++
	postInfo, err := ParseForPost(postPart, g.pkgPrefix)
	if err != nil {
		return fmt.Errorf("parse for post: %w", err)
	}

	g.writeLine("{")
	g.indent++

	// 初始化
	g.writeLine("ctx.Set(%s, %s)", strconv.Quote(initInfo.VarName), initInfo.ValueCode)

	// for 循环
	g.writeLine("for %s {", condCode)
	g.indent++

	// 循环体
	if err := g.generateNodes(n.Body); err != nil {
		return err
	}

	// 后置语句
	g.writeLine("ctx.Set(%s, %s)", strconv.Quote(postInfo.VarName), postInfo.Code)

	g.indent--
	g.writeLine("}")

	g.indent--
	g.writeLine("}")
	return nil
}

// ==================== 代码块 @{} ====================

func (g *CodeGenerator) generateCode(n *CodeNode) error {
	// @{} 块作为回退机制，使用解释器
	g.varCounter++
	errVar := fmt.Sprintf("_codeErr%d", g.varCounter)
	g.writeLine("if %s := ctx.ExecCode(%s); %s != nil { return %s }",
		errVar, strconv.Quote(n.Code), errVar, errVar)
	return nil
}

// ==================== use 节点 ====================

func (g *CodeGenerator) generateUse(n *UseNode) error {
	g.writeLine("{")
	g.indent++

	// 生成 covers 映射
	g.varCounter++
	coversVar := fmt.Sprintf("_covers%d", g.varCounter)
	g.writeLine("%s := make(map[string]func(*%sStaticContext) error)", coversVar, g.pkgPrefix)

	for _, cover := range n.Covers {
		g.varCounter++
		coverFnVar := fmt.Sprintf("_coverFn%d", g.varCounter)
		g.writeLine("%s := func(ctx *%sStaticContext) error {", coverFnVar, g.pkgPrefix)
		g.indent++
		if err := g.generateNodes(cover.Body); err != nil {
			return err
		}
		g.writeLine("return nil")
		g.indent--
		g.writeLine("}")
		g.writeLine("%s[%s] = %s", coversVar, strconv.Quote(cover.Name), coverFnVar)
	}

	// 检查目标是否在同一生成文件中，如果是，直接函数调用
	targetFunc, isKnown := g.resolveUsePath(n.Path)

	g.varCounter++
	oldCoversVar := fmt.Sprintf("_oldCovers%d", g.varCounter)
	g.writeLine("%s := ctx.SwapCovers(%s)", oldCoversVar, coversVar)

	if isKnown {
		// 直接函数调用（全静态）
		g.varCounter++
		errVar := fmt.Sprintf("_useErr%d", g.varCounter)
		g.writeLine("if %s := %s(ctx); %s != nil { ctx.SwapCovers(%s); return %s }",
			errVar, targetFunc, errVar, oldCoversVar, errVar)
	} else {
		// 回退到 UseTemplate（可能走动态）
		g.varCounter++
		errVar := fmt.Sprintf("_useErr%d", g.varCounter)
		g.writeLine("if %s := ctx.UseTemplate(%s, %s); %s != nil { ctx.SwapCovers(%s); return %s }",
			errVar, strconv.Quote(n.Path), coversVar, errVar, oldCoversVar, errVar)
	}

	g.writeLine("ctx.SwapCovers(%s)", oldCoversVar)

	g.indent--
	g.writeLine("}")
	return nil
}

// resolveUsePath 解析 @use 路径，返回目标函数名（如果在同一生成文件中）
func (g *CodeGenerator) resolveUsePath(path string) (string, bool) {
	parts := strings.Split(path, ".")
	if len(parts) < 2 {
		return "", false
	}

	baseKey := parts[0] + "." + parts[1]
	baseFuncName, ok := g.knownKeys[baseKey]
	if !ok {
		return "", false
	}

	if len(parts) == 2 {
		return baseFuncName, true
	}

	// 嵌套 define: test.sql4.a → _gosql_static_test_sql4__a
	funcName := baseFuncName
	for _, defName := range parts[2:] {
		funcName += "__" + sanitizeName(defName)
	}
	return funcName, true
}

// ==================== define 节点 ====================
// define 编译为独立的顶层函数，通过直接调用组合

func (g *CodeGenerator) generateDefine(n *DefineNode) error {
	// 函数名
	defFuncName := g.funcPrefix + "__" + sanitizeName(n.Name)

	// 在当前函数中生成调用
	g.varCounter++
	errVar := fmt.Sprintf("_defErr%d", g.varCounter)
	g.writeLine("if %s := %s(ctx); %s != nil { return %s }", errVar, defFuncName, errVar, errVar)

	// 切换到新缓冲区生成 define 函数
	g.pushBuf()
	savedIndent := g.indent
	savedCounter := g.varCounter
	savedPrefix := g.funcPrefix

	g.indent = 1
	g.varCounter = 0
	g.funcPrefix = defFuncName

	// define 函数体
	g.writeLine("_fullPath := ctx.PushDefine(%s)", strconv.Quote(n.Name))
	g.writeLine("defer ctx.PopDefine()")

	// 检查 cover
	g.varCounter++
	coverFnVar := fmt.Sprintf("_coverFn%d", g.varCounter)
	g.writeLine("if %s := ctx.GetCover(_fullPath, %s); %s != nil {",
		coverFnVar, strconv.Quote(n.Name), coverFnVar)
	g.indent++
	g.writeLine("return %s(ctx)", coverFnVar)
	g.indent--
	g.writeLine("}")

	// 默认内容
	if err := g.generateNodes(n.Body); err != nil {
		// 恢复状态
		g.popBuf()
		g.indent = savedIndent
		g.varCounter = savedCounter
		g.funcPrefix = savedPrefix
		return err
	}

	// 收集 define 函数
	body := g.popBuf()
	g.indent = savedIndent
	g.varCounter = savedCounter
	g.funcPrefix = savedPrefix

	var funcCode strings.Builder
	funcCode.WriteString(fmt.Sprintf("func %s(ctx *%sStaticContext) error {\n", defFuncName, g.pkgPrefix))
	funcCode.WriteString(body)
	funcCode.WriteString("\treturn nil\n")
	funcCode.WriteString("}\n")

	g.defineFuncs = append(g.defineFuncs, funcCode.String())
	return nil
}

// ==================== 条件行节点 ====================

func (g *CodeGenerator) generateConditionalLine(n *ConditionalLineNode) error {
	condCode, err := CompileConditionToGo(n.Condition, g.pkgPrefix)
	if err != nil {
		return fmt.Errorf("compile conditional line %q: %w", n.Condition, err)
	}

	g.writeLine("if %s {", condCode)
	g.indent++
	if err := g.generateNodes(n.LineNodes); err != nil {
		return err
	}
	g.indent--
	g.writeLine("}")
	return nil
}

// ==================== 函数块节点 @func() {} ====================

func (g *CodeGenerator) generateFuncBlock(n *FuncBlockNode) error {
	// 解析函数表达式
	funcInfo, err := ParseFuncCallExpr(n.FuncExpr, g.pkgPrefix)
	if err != nil {
		return fmt.Errorf("parse func block expr %q: %w", n.FuncExpr, err)
	}

	g.writeLine("{")
	g.indent++

	// 保存外层 ctx，用子上下文遮蔽 ctx 变量名
	// 这样 body 中的 ctx.WriteSQL / ctx.AppendArg 等调用自然写入子上下文
	g.varCounter++
	outerCtxVar := fmt.Sprintf("_outerCtx%d", g.varCounter)
	g.writeLine("%s := ctx", outerCtxVar)
	g.writeLine("ctx = %s.SubContext()", outerCtxVar)

	// 生成 body（此时 ctx 已指向子上下文，body 中的 ctx 调用都写入子上下文）
	if err := g.generateNodes(n.Body); err != nil {
		return err
	}

	// 构建查询
	g.varCounter++
	queryVar := fmt.Sprintf("_query%d", g.varCounter)
	g.writeLine("%s := ctx.BuildPtr()", queryVar)

	// 恢复外层 ctx
	g.writeLine("ctx = %s", outerCtxVar)

	// 调用函数块
	argsStr := ""
	if len(funcInfo.Args) > 0 {
		argsStr = ", " + strings.Join(funcInfo.Args, ", ")
	}
	g.writeLine("ctx.CallFuncBlock(%s, %s%s)", strconv.Quote(funcInfo.FuncName), queryVar, argsStr)

	// 将结果写入当前上下文
	g.writeLine("ctx.WriteQuery(%s)", queryVar)

	g.indent--
	g.writeLine("}")
	return nil
}

// ==================== 辅助函数 ====================

// sanitizeFuncName 将模板 key 转换为合法的 Go 函数名
func sanitizeFuncName(key string) string {
	name := strings.ReplaceAll(key, ".", "_")
	name = strings.ReplaceAll(name, "-", "_")
	name = strings.ReplaceAll(name, " ", "_")
	return "_gosql_static_" + name
}

// sanitizeName 清理名称（用于 define 函数名后缀）
func sanitizeName(name string) string {
	name = strings.ReplaceAll(name, ".", "_")
	name = strings.ReplaceAll(name, "-", "_")
	name = strings.ReplaceAll(name, " ", "_")
	return name
}
